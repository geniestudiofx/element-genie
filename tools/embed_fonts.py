# Embeds ext/cinefonts/*.ttf into src/fonts_cine.cpp as a lookup table of built-in fonts.
import os, sys
root = os.path.join(os.path.dirname(__file__), '..')
fonts = [  # display name, file
    ("Anton", "Anton-Regular.ttf"), ("Audiowide", "Audiowide-Regular.ttf"), ("Bebas Neue", "BebasNeue-Regular.ttf"),
    ("Black Ops One", "BlackOpsOne-Regular.ttf"), ("Bungee", "Bungee-Regular.ttf"), ("Cinzel", "Cinzel-Black.ttf"),
    ("Cinzel Decorative", "CinzelDecorative-Black.ttf"), ("Orbitron", "Orbitron-Black.ttf"), ("Pirata One", "PirataOne-Regular.ttf"),
    ("Playfair Display", "PlayfairDisplay-Black.ttf"), ("Russo One", "RussoOne-Regular.ttf"),
]
out = ['// generated by tools/embed_fonts.py - cinematic title fonts (SIL OFL 1.1)', '#include "fonts_cine.h"']
for i, (n, f) in enumerate(fonts):
    b = open(os.path.join(root, 'ext', 'cinefonts', f), 'rb').read()
    out.append('static const unsigned char F%d[] = {%s};' % (i, ','.join(str(x) for x in b)))
out.append('const CineFont g_cine_fonts[] = {' + ','.join('{"%s", F%d, %d}' % (n, i, len(open(os.path.join(root, 'ext', 'cinefonts', f), 'rb').read())) for i, (n, f) in enumerate(fonts)) + '};')
out.append('const int g_cine_font_count = %d;' % len(fonts))
open(os.path.join(root, 'src', 'fonts_cine.cpp'), 'w').write('\n'.join(out) + '\n')
